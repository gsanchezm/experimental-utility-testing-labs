"""Builds the mobile-runner admissibility block of e06-measured-execution.yml from the G-7 block of e03-measured-execution.yml.

DRAFT (operation OP-PREP-E06-EXECUTOR). The rule of protocol/mobile-runner-policy-v3.md, sections 9.5 and 9.7.9 to 9.7.11, is implemented once, in the G-7
block of the E03 measured-execution workflow (operation OP-CI-14; the E06 SUT-01 smoke workflow carries the same copy as its G-9 block). This module
copies that block instead of re-deriving it, and applies the few changes that E06 needs. Every change is a string replacement that must apply exactly
once, so that a change of the source block fails loudly here instead of drifting silently:

  T1  the multiplication sign in the requirement-1 clause is written as a unicode escape (the E06 workflow files are ASCII);
  T2  the Smoke records reader accepts the exact QUALIFIER records of both assigned SUTs (SUT-01 and SUT-02) instead of the prefix
      qualification/compatibility-smoke/, which does not match the SUT-01 record (qualification/compatibility-smoke-sut01/README.md);
  T3  the per-condition read of the QUALIFIER record uses the same exact allowlist;
  T4  two additional gates, never relaxing one: a SUT-01 FAIL_RUNNER row of the selected runner is unresolved (the lineage retains only the one named
      SUT-02 x iOS row), and the smoke entry of the condition must point to the QUALIFIER record of its own SUT;
  T5  the block runs inside try/except, so a missing or unreadable record is reported as a failed gate and writes ready=false (the E03 block raises).

Usage: python3 tests/lift_g7.py --check   (exit 1 when the E06 workflow does not hold the block this module builds)
       python3 tests/lift_g7.py --write   (replace the marked region of the E06 workflow with the built block)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..'))
E03 = os.path.join(REPO, '.github', 'workflows', 'e03-measured-execution.yml')
E06 = os.path.join(REPO, '.github', 'workflows', 'e06-measured-execution.yml')

SRC_BEGIN = '          # G-7 mobile runner for mobile cells'
SRC_END = '          # G-8 controlled instance verified for this condition on GitHub Actions'
BEGIN = '          # BEGIN lifted G-7 block: generated by executor/tests/lift_g7.py from the G-7 block of e03-measured-execution.yml; never edited by hand'
END = '          # END lifted G-7 block'
IF_LINE = "          if surface in ('ANDROID', 'IOS'):"
IND = ' ' * 14

QUALIFIER_RECORDS = [
    IND + "# The QUALIFIER records, one per assigned SUT: the only files a Smoke records row of E06 may come from (an exact allowlist, not a prefix).",
    IND + "QUALIFIER_RECORDS = {'SUT-01': 'qualification/compatibility-smoke-sut01/README.md', 'SUT-02': 'qualification/compatibility-smoke/README.md'}",
]

SUT01_FAIL_GATE = [
    IND + "# E06 addition: the lineage record retains only the one SUT-02 x iOS FAIL_RUNNER that it names; a FAIL_RUNNER of the selected runner in the",
    IND + "# SUT-01 QUALIFIER record is unresolved (policy v3, 9.5: any SUT x platform).",
    IND + "sut01_fail = [r for r in smoke_rows(QUALIFIER_RECORDS['SUT-01']) if r[7] == 'FAIL_RUNNER' and of_runner(r)]",
    IND + "gate('no FAIL_RUNNER of the selected runner in the SUT-01 QUALIFIER record (E06 addition: the remediation lineage retains only the SUT-02 x ios row)', not sut01_fail, str([(r[0], r[1], row_auth(r)) for r in sut01_fail]))",
]

QR_GATE = [
    IND + "gate('the smoke entry points to the QUALIFIER record of its own SUT (E06 addition: the exact allowlist of the SUT-01 and SUT-02 records)', qr == QUALIFIER_RECORDS.get(sut), qr or '(absent)')",
]


def once(text, old, new):
    count = text.count(old)
    if count != 1:
        raise SystemExit(f'lift_g7: expected exactly one occurrence, found {count}: {old[:90]!r}')
    return text.replace(old, new)


def source_region():
    with open(E03, encoding='utf-8') as f:
        lines = f.read().split('\n')
    starts = [i for i, l in enumerate(lines) if l.startswith(SRC_BEGIN)]
    ends = [i for i, l in enumerate(lines) if l == SRC_END]
    if len(starts) != 1 or len(ends) != 1 or ends[0] <= starts[0]:
        raise SystemExit('lift_g7: the G-7 block of the E03 workflow was not found exactly once')
    return lines[starts[0]:ends[0]]


def build_block():
    region = source_region()
    idx = [i for i, l in enumerate(region) if l == IF_LINE]
    if len(idx) != 1:
        raise SystemExit('lift_g7: the mobile-cell condition line was not found exactly once')
    head, body = region[:idx[0] + 1], region[idx[0] + 1:]
    text = '\n'.join(body)
    # T1
    text = once(text, ".replace('\u00d7', 'x')", ".replace('\\u00d7', 'x')")
    # T2
    text = once(text, "if str(path).startswith('qualification/compatibility-smoke/') and os.path.isfile(path):",
                "if path in QUALIFIER_RECORDS.values() and os.path.isfile(path):")
    # T3
    text = once(text, "if qr.startswith('qualification/compatibility-smoke/') and os.path.isfile(qr):",
                "if qr == QUALIFIER_RECORDS.get(sut) and os.path.isfile(qr):")
    # T4
    first_condition_line = IND + "ents = [e for e in (smk.get('entries') or []) if isinstance(e, dict) and e.get('sut_id') == sut and e.get('platform') == plat and e.get('runner') == runner]"
    text = once(text, first_condition_line, '\n'.join(SUT01_FAIL_GATE) + '\n' + first_condition_line)
    qr_line = IND + "qr = str(sm1.get('qualifier_record') or '')"
    text = once(text, qr_line, qr_line + '\n' + '\n'.join(QR_GATE))
    body = (QUALIFIER_RECORDS + text.split('\n'))
    # T5
    out = list(head)
    out.append(' ' * 14 + 'try:')
    out.extend((' ' * 4 + l) if l.strip() else l for l in body)
    out.append(' ' * 14 + 'except Exception as ex:')
    out.append(' ' * 18 + "gate('the mobile-runner admissibility checks completed without an exception', False, repr(ex))")
    return '\n'.join([BEGIN] + out + [END]) + '\n'


def current_region(workflow_text):
    lines = workflow_text.split('\n')
    starts = [i for i, l in enumerate(lines) if l == BEGIN]
    ends = [i for i, l in enumerate(lines) if l == END]
    if len(starts) != 1 or len(ends) != 1 or ends[0] <= starts[0]:
        return None, None
    return lines, (starts[0], ends[0])


def main(argv):
    built = build_block()
    with open(E06, encoding='utf-8') as f:
        text = f.read()
    lines, span = current_region(text)
    if '--write' in argv:
        if span is None:
            raise SystemExit('lift_g7: the E06 workflow has no BEGIN/END markers to replace')
        new = lines[:span[0]] + built.rstrip('\n').split('\n') + lines[span[1] + 1:]
        with open(E06, 'w', encoding='utf-8', newline='\n') as f:
            f.write('\n'.join(new))
        print('wrote the lifted block')
        return 0
    if span is None:
        print('the E06 workflow has no lifted block')
        return 1
    have = '\n'.join(lines[span[0]:span[1] + 1]) + '\n'
    if have != built:
        print('the lifted block of the E06 workflow differs from the one built from the E03 workflow')
        return 1
    print('the lifted block equals the one built from the E03 workflow')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
