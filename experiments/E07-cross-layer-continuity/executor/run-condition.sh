#!/usr/bin/env bash
# E07-cross-layer-continuity executor entry point. DRAFT (operation OP-PREP-E07-04): not frozen, not locked.
# Invoked by .github/workflows/e07-measured-execution.yml (MEASURED_EXPERIMENT), by the DRY_RUN step of
# .github/workflows/e07-environment-verification.yml, or by hand for a DEVELOPMENT run. It verifies every other implementation
# file against the digests below, then runs the executions of ONE condition on its shared instance with python3 -m executor.run:
# one bundle per execution under OUTPUT_DIR/executions/<run_id>/ (run-manifest.json last in each) and one condition-summary.json.
# Exit status 0 when every execution that began has a run manifest (SUCCESS, FAILURE, ABORTED, and ERROR are recorded outcomes, and so
# is every category of D-E07-10); 1 when an execution has none; 2 when the executor refused the run before it began (no record written).
# No retry logic anywhere. python3 on PATH must be the interpreter where requirements.txt is installed (--require-hashes).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Implementation digests (sha256 and repository path relative to this directory), verified before anything else.
# Generated by experiments/E07-cross-layer-continuity/executor/tests/embed_digests.py; do not type them by hand.
DIGESTS='
