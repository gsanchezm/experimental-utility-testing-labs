#!/usr/bin/env bash
# E09-accessibility executor entry point. DRAFT (operation OP-PREP-E09): not frozen, not locked.
# Invoked by .github/workflows/e09-measured-execution.yml (MEASURED_EXPERIMENT), by the DRY_RUN step of
# .github/workflows/e09-environment-verification.yml, or by hand for a DEVELOPMENT run. It verifies every other
# implementation file against the digests below, then runs one attempt with python3 -m "$ENTRY_MODULE" (executor.run by
# default; executor.verify for the environment verification, which writes verification.json and no run manifest).
# Exit status 0 whenever a run manifest was written (SUCCESS, FAILURE, INCONCLUSIVE, ABORTED, and ERROR are recorded
# outcomes); non-zero only when no manifest could be written (or, for executor.verify, when a check did not pass).
# python3 on PATH must be the interpreter where requirements.txt is installed (--require-hashes). No retry logic anywhere.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Implementation digests (sha256 and repository path relative to this directory), verified before anything else.
# Generated by experiments/E09-accessibility/executor/tests/embed_digests.py; do not type them by hand.
DIGESTS='
